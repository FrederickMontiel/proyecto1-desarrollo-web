-- --------------------------------------------------------------------------------------
-- Esquema del Alert Service.
--
-- Nivel, fenómeno y estado se guardan como smallint con el mismo valor que tenían en la
-- Fase 2 (NivelAlerta: 0 Verde … 3 Rojo; TipoFenomeno: 0 Ninguno … 5 IncendioForestal;
-- EstadoAlerta: 0 Activa, 1 Atendida, 2 Cerrada): ordenar por nivel es ordenar por
-- severidad, y la migración copia los números tal cual.
--
-- Los id son IDENTITY BY DEFAULT para poder insertar con los id de la Fase 2.
-- comunidad_id y sensor_id son referencias lógicas a otros servicios: no hay FK.
-- --------------------------------------------------------------------------------------

CREATE TABLE reglas_alerta (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             varchar(120)   NOT NULL,
    tipo_sensor        varchar(20)    NOT NULL,
    valor_minimo       numeric(10, 3) NULL,
    valor_maximo       numeric(10, 3) NULL,
    nivel              smallint       NOT NULL,
    fenomeno           smallint       NOT NULL,
    mensaje            varchar(500)   NOT NULL,
    activa             boolean        NOT NULL DEFAULT true,
    fecha_creacion     timestamptz    NOT NULL DEFAULT now(),
    fecha_modificacion timestamptz    NULL,
    CONSTRAINT ck_regla_rango CHECK (valor_minimo IS NOT NULL OR valor_maximo IS NOT NULL)
);
CREATE UNIQUE INDEX ux_reglas_nombre ON reglas_alerta (lower(nombre));
CREATE INDEX ix_reglas_tipo_activa ON reglas_alerta (tipo_sensor, activa);

CREATE TABLE umbrales_sensor (
    sensor_id          integer        PRIMARY KEY,
    tipo_sensor        varchar(20)    NOT NULL,
    amarillo_alto      numeric(10, 3) NULL,
    naranja_alto       numeric(10, 3) NULL,
    rojo_alto          numeric(10, 3) NULL,
    amarillo_bajo      numeric(10, 3) NULL,
    naranja_bajo       numeric(10, 3) NULL,
    rojo_bajo          numeric(10, 3) NULL,
    fecha_modificacion timestamptz    NOT NULL DEFAULT now()
);

CREATE TABLE alertas (
    id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version                   bigint         NOT NULL DEFAULT 0,
    comunidad_id              integer        NOT NULL,
    comunidad_nombre          varchar(120)   NOT NULL DEFAULT '',
    sensor_id                 integer        NULL,
    sensor_codigo             varchar(30)    NULL,
    sensor_nombre             varchar(120)   NULL,
    unidad_medida             varchar(15)    NULL,
    nivel                     smallint       NOT NULL,
    fenomeno                  smallint       NOT NULL,
    mensaje                   varchar(600)   NOT NULL,
    valor_disparo             numeric(10, 3) NULL,
    umbral                    numeric(10, 3) NULL,
    regla_id                  bigint         NULL,
    regla_nombre              varchar(150)   NOT NULL DEFAULT '',
    estado                    smallint       NOT NULL DEFAULT 0,
    fecha_hora                timestamptz    NOT NULL DEFAULT now(),
    fecha_cierre              timestamptz    NULL,
    fecha_modificacion        timestamptz    NULL,
    ciclos_sin_riesgo         integer        NOT NULL DEFAULT 0,
    reconocida                boolean        NOT NULL DEFAULT false,
    reconocida_por_usuario_id integer        NULL,
    reconocida_por            varchar(160)   NULL,
    fecha_reconocimiento      timestamptz    NULL,
    cerrada_por_usuario_id    integer        NULL,
    cerrada_por               varchar(160)   NULL
);
-- Cada ciclo busca las abiertas de cada comunidad: índice parcial solo sobre ellas.
CREATE INDEX ix_alertas_abiertas ON alertas (comunidad_id) WHERE fecha_cierre IS NULL;
CREATE INDEX ix_alertas_fecha ON alertas (fecha_hora DESC);
CREATE INDEX ix_alertas_comunidad_fecha ON alertas (comunidad_id, fecha_hora DESC);
-- Una sola alerta abierta por fenómeno y comunidad, garantizado por el motor y no solo por el código.
CREATE UNIQUE INDEX ux_alertas_abierta_fenomeno ON alertas (comunidad_id, fenomeno) WHERE fecha_cierre IS NULL;

CREATE TABLE eventos_historial (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comunidad_id           integer        NOT NULL,
    comunidad_nombre       varchar(120)   NOT NULL DEFAULT '',
    alerta_id              bigint         NULL REFERENCES alertas (id) ON DELETE SET NULL,
    fenomeno               smallint       NOT NULL,
    nivel_maximo           smallint       NOT NULL,
    descripcion            varchar(600)   NOT NULL,
    origen_sensor          varchar(160)   NOT NULL DEFAULT '',
    sensor_id              integer        NULL,
    valor_registrado       numeric(10, 3) NULL,
    estado                 smallint       NOT NULL DEFAULT 0,
    usuario_responsable_id integer        NULL,
    usuario_responsable    varchar(160)   NULL,
    fecha_inicio           timestamptz    NOT NULL DEFAULT now(),
    fecha_fin              timestamptz    NULL,
    fecha_modificacion     timestamptz    NULL
);
CREATE INDEX ix_eventos_fecha ON eventos_historial (fecha_inicio DESC);
CREATE INDEX ix_eventos_alerta ON eventos_historial (alerta_id);
CREATE INDEX ix_eventos_comunidad_fecha ON eventos_historial (comunidad_id, fecha_inicio DESC);
